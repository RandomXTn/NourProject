import { type ClassValue, clsx } from "clsx";
import { twMerge } from "tailwind-merge";

export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs));
}

/**
 * Format millimes (1/1000 TND) to a display string.
 * e.g. 45000 → "45,000 DT"
 */
export function formatPrice(millimes: number, locale = "fr-TN"): string {
  const tnd = millimes / 1000;
  return new Intl.NumberFormat(locale, {
    minimumFractionDigits: 3,
    maximumFractionDigits: 3,
  }).format(tnd) + " DT";
}

export function formatPriceRaw(millimes: number): number {
  return millimes / 1000;
}

/** Convert TND float to millimes integer */
export function toMillimes(tnd: number): number {
  return Math.round(tnd * 1000);
}

export function generateOrderNumber(): string {
  const timestamp = Date.now().toString(36).toUpperCase();
  const random = Math.random().toString(36).substring(2, 6).toUpperCase();
  return `NR-${timestamp}-${random}`;
}

export function truncate(str: string, length: number): string {
  if (str.length <= length) return str;
  return str.slice(0, length) + "…";
}

export function slugify(str: string): string {
  return str
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9\s-]/g, "")
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-")
    .trim();
}

